"""Rule to framework control mapping, informed by seven frameworks, plus a coverage report.

Mappings live in mappings/<framework>.yaml and identifier lists in mappings/identifiers/.
The mapping says which controls a rule is informed by. It is not a compliance claim.
"""

from __future__ import annotations

import argparse
import os
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any

import yaml

from cspm.contracts.finding import ControlRef
from cspm.contracts.rule_ids import RULE_IDS

REPO_ROOT = Path(__file__).resolve().parents[2]
MIN_FAMILIES = 3


@dataclass(frozen=True, slots=True)
class MappingRow:
    rule_id: str
    control_id: str
    rationale: str


@dataclass(frozen=True, slots=True)
class Framework:
    key: str
    name: str
    family: str
    note: str
    identifiers: tuple[str, ...]
    labels: Mapping[str, str]
    mappings: tuple[MappingRow, ...]


def mappings_dir() -> Path:
    """CSPM_MAPPINGS_DIR wins so an installed package can point at a copied mappings folder."""
    return Path(os.environ.get("CSPM_MAPPINGS_DIR", REPO_ROOT / "mappings"))


def _read_identifiers(path: Path) -> tuple[tuple[str, ...], dict[str, str]]:
    ids: list[str] = []
    labels: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        ident, _, label = line.partition(" ")
        ids.append(ident)
        if label.strip():
            labels[ident] = label.strip()
    return tuple(ids), labels


def _load_framework(path: Path) -> Framework:
    data: dict[str, Any] = yaml.safe_load(path.read_text(encoding="utf-8"))
    key = str(data["framework"])
    ids, labels = _read_identifiers(path.parent / "identifiers" / f"{key}.txt")
    rows = []
    for rule_id, entries in (data.get("mappings") or {}).items():
        for entry in entries:
            rows.append(MappingRow(str(rule_id), str(entry["control"]), str(entry["rationale"])))
    return Framework(
        key=key,
        name=str(data["name"]),
        family=str(data.get("family", key)),
        note=str(data.get("note", "")),
        identifiers=ids,
        labels=labels,
        mappings=tuple(rows),
    )


@lru_cache(maxsize=4)
def load_frameworks(directory: Path | None = None) -> tuple[Framework, ...]:
    """Load every framework file, sorted by key for stable output."""
    root = directory or mappings_dir()
    return tuple(_load_framework(p) for p in sorted(root.glob("*.yaml")))


def controls_for(rule_id: str) -> list[ControlRef]:
    """Controls a rule is informed by, across all frameworks, in a stable order."""
    return [
        ControlRef(framework=fw.key, control_id=m.control_id)
        for fw in load_frameworks()
        for m in fw.mappings
        if m.rule_id == rule_id
    ]


def validate(frameworks: Sequence[Framework] | None = None) -> list[str]:
    """Problems with the mapping set: unknown rules or identifiers, empty rationale, too few frameworks."""
    fws = load_frameworks() if frameworks is None else tuple(frameworks)
    known_rules = {r.id for r in RULE_IDS}
    problems: list[str] = []
    families: dict[str, set[str]] = {r: set() for r in known_rules}
    for fw in fws:
        allowed = set(fw.identifiers)
        for m in fw.mappings:
            if m.rule_id not in known_rules:
                problems.append(f"{fw.key}: unknown rule {m.rule_id}")
                continue
            if m.control_id not in allowed:
                problems.append(f"{fw.key}: {m.rule_id} maps to unknown identifier {m.control_id}")
            if not m.rationale.strip():
                problems.append(f"{fw.key}: {m.rule_id} -> {m.control_id} has no rationale")
            families[m.rule_id].add(fw.family)
    for rule_id in sorted(known_rules):
        if len(families[rule_id]) < MIN_FAMILIES:
            problems.append(f"{rule_id}: maps to {len(families[rule_id])} frameworks, need {MIN_FAMILIES}")
    return problems


def coverage_markdown(frameworks: Sequence[Framework] | None = None) -> str:
    """Per framework: controls referenced, rules per control and listed controls with no rule."""
    fws = load_frameworks() if frameworks is None else tuple(frameworks)
    out = [
        "# Mapping coverage",
        "",
        "Generated by `python -m cspm.mapping`. Do not edit by hand.",
        "",
        "Rules are informed by these frameworks. This is not a compliance or certification claim.",
        "Identifier lists are local and may be a subset of each framework.",
        "",
        "| Framework | Listed identifiers | Referenced | Mappings | Rules mapped |",
        "|---|---|---|---|---|",
    ]
    for fw in fws:
        referenced = {m.control_id for m in fw.mappings}
        rules = {m.rule_id for m in fw.mappings}
        out.append(f"| {fw.name} | {len(fw.identifiers)} | {len(referenced)} | {len(fw.mappings)} | {len(rules)} |")
    for fw in fws:
        per_control: dict[str, list[str]] = {}
        for m in fw.mappings:
            per_control.setdefault(m.control_id, []).append(m.rule_id)
        out += ["", f"## {fw.name}", ""]
        if fw.note:
            out += [fw.note, ""]
        out += ["| Control | Rules |", "|---|---|"]
        for ident in fw.identifiers:
            if ident in per_control:
                label = f" ({fw.labels[ident]})" if ident in fw.labels else ""
                out.append(f"| {ident}{label} | {', '.join(sorted(set(per_control[ident])))} |")
        unmapped = [i for i in fw.identifiers if i not in per_control]
        out += ["", f"Controls with no rule ({len(unmapped)}): " + (", ".join(unmapped) if unmapped else "none")]
    out += ["", "## Frameworks per rule", "", "| Rule | Frameworks |", "|---|---|"]
    for rule in RULE_IDS:
        fams = sorted({fw.family for fw in fws for m in fw.mappings if m.rule_id == rule.id})
        out.append(f"| {rule.id} | {len(fams)}: {' '.join(fams)} |")
    return "\n".join(out) + "\n"


def write_coverage(path: Path | None = None) -> Path:
    """Validate the mappings, then write the coverage report. Raises ValueError on any problem."""
    problems = validate()
    if problems:
        raise ValueError("mapping problems:\n" + "\n".join(problems))
    target = path or REPO_ROOT / "docs" / "mapping-coverage.md"
    target.write_text(coverage_markdown(), encoding="utf-8", newline="\n")
    return target


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point for `python -m cspm.mapping` and the `cspm map-coverage` command."""
    parser = argparse.ArgumentParser(prog="cspm map-coverage", description=main.__doc__)
    parser.add_argument("--out", type=Path, default=None, help="output path (default docs/mapping-coverage.md)")
    parser.add_argument("--check", action="store_true", help="validate only and write nothing")
    args = parser.parse_args(argv)
    if args.check:
        problems = validate()
        for p in problems:
            print(p)
        return 1 if problems else 0
    try:
        written = write_coverage(args.out)
    except ValueError as exc:
        print(exc)
        return 1
    print(f"wrote {written}")
    return 0


__all__ = ["Framework", "controls_for", "coverage_markdown", "load_frameworks", "main", "validate", "write_coverage"]
